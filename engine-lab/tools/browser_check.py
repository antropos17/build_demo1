import json, os, shutil
from pathlib import Path
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'dist'/'verification'
OUT.mkdir(parents=True,exist_ok=True)
html=(ROOT/'dist/last-piston.html').read_text().replace('<body>','<body><script>window.__PISTON_TEST__=true;</script>')
report={'checks':[], 'console_errors':[]}
def ok(name,condition):
 assert condition,name
 report['checks'].append(name)
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path=os.environ.get('CHROMIUM_PATH') or shutil.which('chromium'),args=['--no-sandbox','--disable-dev-shm-usage','--autoplay-policy=no-user-gesture-required'])
 page=browser.new_page(viewport={'width':1280,'height':1120},device_scale_factor=1)
 page.on('pageerror',lambda e:report['console_errors'].append(str(e)))
 page.set_content(html,wait_until='load')
 page.wait_for_function('window.__engineLab !== undefined')
 page.evaluate('__engineLab.pause()')
 ok('desktop no horizontal overflow',page.evaluate('document.documentElement.scrollWidth <= innerWidth'))
 page.screenshot(path=OUT/'Last-Piston-07-clean.png',full_page=True)
 from PIL import Image, ImageStat
 im=Image.open(OUT/'Last-Piston-07-clean.png').convert('RGB')
 stats=ImageStat.Stat(im.crop((250,230,1000,600)))
 ok('desktop screenshot contains rendered engine pixels',sum(stats.var)>200)
 page.keyboard.down('Space');page.wait_for_timeout(120)
 ok('keyboard throttle engages',page.evaluate('__engineLab.held'))
 page.keyboard.down('ArrowUp');page.keyboard.up('Space')
 ok('releasing one key does not release another held key',page.evaluate('__engineLab.held'))
 page.keyboard.up('ArrowUp')
 ok('keyboard throttle releases',not page.evaluate('__engineLab.held'))
 page.locator('#gas').dispatch_event('pointerdown',{'pointerId':10,'pointerType':'touch','button':0})
 ok('touch throttle engages',page.evaluate('__engineLab.held'))
 page.locator('#gas').dispatch_event('pointercancel',{'pointerId':10,'pointerType':'touch'})
 ok('touch cancel releases throttle',not page.evaluate('__engineLab.held'))
 page.keyboard.down('Space');page.evaluate('window.dispatchEvent(new Event("blur"))')
 ok('window blur releases throttle',not page.evaluate('__engineLab.held'));page.keyboard.up('Space')
 page.evaluate('__engineLab.advance(70,true,true)')
 state=page.evaluate('({active:__engineLab.engine.activeCount,rpm:__engineLab.engine.rpm,smoke:__engineLab.renderer.smoke.length,damage:__engineLab.engine.damage,time:__engineLab.engine.time})')
 report['at_70_seconds']=state
 ok('visual simulation reaches one cylinder',state['active']==1)
 page.screenshot(path=OUT/'Last-Piston-07-survivor.png',full_page=True)
 page.evaluate('__engineLab.advance(100,true,true)')
 pools=page.evaluate('({smoke:__engineLab.renderer.smoke.length,drops:__engineLab.renderer.drops.length,debris:__engineLab.renderer.debris.length,trace:__engineLab.renderer.trace.length,rings:__engineLab.renderer.rings.length,film:__engineLab.engine.film,components:__engineLab.engine.components})')
 report['after_170_seconds']=pools
 ok('particle and telemetry memory stays bounded',pools['smoke']<=225 and pools['drops']<=65 and pools['debris']<=76 and pools['trace']<=140 and pools['rings']<=6)
 page.screenshot(path=OUT/'Last-Piston-07-damaged.png',full_page=True)
 page.evaluate('window.snap=__engineLab.engine.snapshot();__engineLab.restore(JSON.parse(JSON.stringify(snap)))')
 ok('journal survives reload',page.evaluate('document.querySelectorAll("#journal li").length===snap.log.length && snap.log.length>0'))
 ok('floor wreckage restored without explosions',page.evaluate('__engineLab.renderer.debris.length===3 && __engineLab.renderer.smoke.length===0'))
 # Audio output validation: inspect the real browser fallback signal rather than just a ready flag.
 page.evaluate('__engineLab.audio.update(__engineLab.engine); window.an=__engineLab.audio.ctx.createAnalyser();an.fftSize=2048;__engineLab.audio.master.connect(an)')
 page.wait_for_timeout(400)
 audio=page.evaluate('(()=>{const a=new Float32Array(an.fftSize);an.getFloatTimeDomainData(a);return {ready:__engineLab.audio.ready,state:__engineLab.audio.ctx.state,backend:__engineLab.audio.node?"worklet":"scheduled-buffer",rms:Math.sqrt(a.reduce((n,x)=>n+x*x,0)/a.length),peak:Math.max(...a.map(Math.abs))}})()')
 report['audio']=audio;ok('browser produces bounded nonzero audio',audio['rms']>.00001 and audio['peak']<1)
 page.locator('.settings summary').click()
 page.locator('#mute').click();ok('mute works',page.evaluate('__engineLab.audio.muted'))
 page.locator('#motion').click();ok('reduced shake setting works',page.evaluate('__engineLab.renderer.reduced'))
 page.locator('#reset').click();ok('reset requires confirmation',page.evaluate('__engineLab.engine.activeCount===1'))
 page.locator('#reset').click();ok('confirmed reset clears damage and journal',page.evaluate('__engineLab.engine.activeCount===4 && document.querySelectorAll("#journal li").length===0'))
 page.close()
 mobile=browser.new_context(viewport={'width':390,'height':844},device_scale_factor=2,is_mobile=True,has_touch=True)
 mp=mobile.new_page();mp.on('pageerror',lambda e:report['console_errors'].append(str(e)))
 mp.set_content(html);mp.wait_for_function('window.__engineLab !== undefined');mp.evaluate('__engineLab.pause()')
 ok('mobile no horizontal overflow',mp.evaluate('document.documentElement.scrollWidth<=innerWidth'))
 ok('mobile preserves mechanical proportions',mp.evaluate('Math.abs(__engineLab.renderer.scale-__engineLab.renderer.sy)<1e-8'))
 mp.locator('#gas').dispatch_event('pointerdown',{'pointerId':17,'pointerType':'touch','button':0})
 ok('mobile touch gas works',mp.evaluate('__engineLab.held'))
 mp.locator('#gas').dispatch_event('lostpointercapture',{'pointerId':17,'pointerType':'touch'})
 ok('lost pointer capture releases throttle',not mp.evaluate('__engineLab.held'))
 mp.evaluate('__engineLab.advance(70,true,true)')
 mp.screenshot(path=OUT/'Last-Piston-07-mobile.png',full_page=True)
 pix=mp.evaluate('(()=>{let r=__engineLab.renderer;const p=r.c.getImageData(Math.round(r.canvas.width/2),Math.round(r.canvas.height/2),1,1).data;return p[0]+p[1]+p[2]})()')
 ok('mobile canvas remains rendered after viewport resize',pix>25)
 report['mobile_button_bounds']=mp.locator('#gas').bounding_box()
 ok('mobile primary control is large enough',report['mobile_button_bounds']['height']>=44)
 ok('no JavaScript runtime errors',len(report['console_errors'])==0)
 browser.close()
Path(OUT/'Last-Piston-07-browser-report.json').write_text(json.dumps(report,indent=2,ensure_ascii=False))
print(json.dumps(report,indent=2,ensure_ascii=False))
